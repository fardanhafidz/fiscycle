const DAYS = ['Sen', 'Sel', 'Rab', 'Kam', 'Jum', 'Sab', 'Min'];

function createHistory(
  ph: number[],
  temp: number[],
  dO: number[],
  ntu: number[]
): TelemetryHistoryPoint[] {
  return DAYS.map((dayLabel, idx) => ({
    dayLabel,
    ph: ph[idx] ?? 7.2,
    temperatureC: temp[idx] ?? 28.0,
    dissolvedOxygenMgL: dO[idx] ?? 6.0,
    turbidityNtu: ntu[idx] ?? 20,
  }));
}

